    private void btnSubmitActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSubmitActionPerformed
        // TODO add your handling code here:
        fname = txtFname.getText();
        mname = txtMname.getText();
        lname = txtLname.getText();
        email = txtEmail.getText();
        password = new String(txtPassword.getPassword());
        
        UserEntity user = new UserEntity(fname, mname, lname, email, password);
        //We will add Dbconnector here next commit
        if(user.hasBlankFields()){
            JOptionPane.showMessageDialog(this, "Some fields are empty!");
        }else{
            try{
                boolean isUserInserted = accountController.registerUser(user);
                if(isUserInserted){
                    JOptionPane.showMessageDialog(this, "User created!");
                    loginForm.setVisible(true);
                    this.setVisible(false);
                }else{
                    JOptionPane.showMessageDialog(this, "User exists");
                }
                
            }catch(Exception e){
            JOptionPane.showMessageDialog(this, "Error Creating User");
            System.out.println(e);
        }
        }
    }//GEN-LAST:event_btnSubmitActionPerformed

