    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        
        try {
            int selectedRow = jTableStudent.getSelectedRow();
            if (selectedRow < 0) {
                javax.swing.JOptionPane.showMessageDialog(this, "Please select a student to delete.");
                return;
            }

            int id = Integer.parseInt(jTableStudent.getValueAt(selectedRow, 0).toString());

            int confirm = javax.swing.JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this student?", "Confirm", javax.swing.JOptionPane.YES_NO_OPTION);
            if (confirm == javax.swing.JOptionPane.YES_OPTION) {
                StudentController controller = new StudentController();
                boolean success = controller.deleteStudent(id);

                if (success) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Student deleted successfully!");
                    loadStudentData();
                    clearFields();
                } else {
                    javax.swing.JOptionPane.showMessageDialog(this, "Failed to delete student.");
                }
            }

        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

