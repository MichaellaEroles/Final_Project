    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
        
        try {
            int selectedRow = jTableStudent.getSelectedRow();
            if (selectedRow < 0) {
                javax.swing.JOptionPane.showMessageDialog(this, "Please select a student to update.");
                return;
            }

            int id = Integer.parseInt(jTableStudent.getValueAt(selectedRow, 0).toString());
            String studentId = txtstudentID.getText();
            String fname = txtfname.getText();
            String mname = txtmname.getText();
            String lname = txtlname.getText();
            String program = txtProgram.getText();

            StudentEntities student = new StudentEntities(id, studentId, fname, mname, lname, program);
            StudentController controller = new StudentController();
            boolean success = controller.updateStudent(student);

            if (success) {
                javax.swing.JOptionPane.showMessageDialog(this, "Student updated successfully!");
                loadStudentData();
                clearFields();
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Failed to update student.");
            }
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

