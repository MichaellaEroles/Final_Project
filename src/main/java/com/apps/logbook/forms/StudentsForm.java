     private void loadStudentData() {
        try {
            StudentController controller = new StudentController();
            List<StudentEntities> students = controller.getAllStudents();

            DefaultTableModel model = new DefaultTableModel();
            model.setColumnIdentifiers(new String[]{"ID", "Student ID", "First Name", "Middle Name", "Last Name", "Program"});

            for (StudentEntities s : students) {
                model.addRow(new Object[]{
                    s.getId(),
                    s.getStudentId(),
                    s.getFirstName(),
                    s.getMiddleName(),
                    s.getLastName(),
                    s.getProgram()
                });
            }

            jTableStudent.setModel(model);

            // Optional: Hide ID column
            jTableStudent.getColumnModel().getColumn(0).setMinWidth(0);
            jTableStudent.getColumnModel().getColumn(0).setMaxWidth(0);

        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error loading data: " + e.getMessage());
        }
    }
     
     
